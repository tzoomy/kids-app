import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { enumerateGameVoiceLines } from '../helpers/gameVoiceLines';
import { loadAudioManifest } from '@/content/loadContent';
import textHashes from '@/content/audio-text-hashes.json';

// scripts/tts/game-lines.json is the render list generate_voice.py uses for game lines. It must match what the
// games actually request. After a copy edit run: UPDATE_GAME_LINES=1 npx vitest run tests/unit/gameVoiceLines.test.ts
const FILE = path.resolve(__dirname, '../../scripts/tts/game-lines.json');
const PREFIX = 'gemini-3.8-flash-tts|Leda|warm, cheerful, slow and clear, speaking to a 2 to 5 year old|';

describe('game voice lines', () => {
  const { lines, conflicts } = enumerateGameVoiceLines();
  const json = { _comment: 'Generated by tests/unit/gameVoiceLines.test.ts (UPDATE_GAME_LINES=1). Voice lines the games request beyond animal-restaurant.json and voice-lines-he.json; rendered by scripts/tts/generate_voice.py.', unrecordable: conflicts, lines };

  it('scripts/tts/game-lines.json matches the lines the games build', () => {
    const text = JSON.stringify(json, null, 2) + '\n';
    if (process.env.UPDATE_GAME_LINES) fs.writeFileSync(FILE, text);
    expect(JSON.parse(fs.readFileSync(FILE, 'utf8'))).toEqual(JSON.parse(text));
  });

  it('every recorded game line was rendered from its current text', () => {
    const manifest = loadAudioManifest();
    const hashes = textHashes as Record<string, string>;
    for (const l of lines) {
      if (!manifest[l.id]) continue;
      const want = crypto.createHash('sha1').update(PREFIX + l.text, 'utf8').digest('hex').slice(0, 12);
      expect(hashes[l.id], l.id).toBe(want);
    }
  });

  it('a line id with more than one text never gets a clip', () => {
    const manifest = loadAudioManifest();
    for (const id of Object.keys(conflicts)) expect(manifest[id], id).toBeUndefined();
  });
});
